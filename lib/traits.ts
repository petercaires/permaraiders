export function getTraitById(id: string): TraitDefinition | undefined {
  return traitDefinitions.find((trait) => trait.id === id)
}

export function getTraitsByCategory(category: string): TraitDefinition[] {
  return traitDefinitions.filter((trait) => trait.category === category)
}

export function getTraitsByRarity(rarity: string): TraitDefinition[] {
  return traitDefinitions.filter((trait) => trait.rarity === rarity)
}
